        g('Z', "#####", "....#", "...#.", "..#..", ".#...", "#....", "#####");
        g('0', ".###.", "#...#", "#..##", "#.#.#", "##..#", "#...#", ".###.");
        g('1', ".#.", "##.", ".#.", ".#.", ".#.", ".#.", "###");
        g('2', ".###.", "#...#", "....#", "...#.", "..#..", ".#...", "#####");
